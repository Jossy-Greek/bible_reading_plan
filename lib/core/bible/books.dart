/// The 66 books of the Protestant canon with their chapter counts.
///
/// Static data: the app ships this table and generates every reading plan
/// from it. Bible text is deliberately absent in v1; when it arrives it hangs
/// off [BibleBook.id] and [ChapterReference] without touching this file.
library;

enum Testament {
  old('Old Testament'),
  newT('New Testament');

  const Testament(this.title);
  final String title;
}

class BibleBook {
  const BibleBook({
    required this.id,
    required this.name,
    required this.abbreviation,
    required this.testament,
    required this.chapters,
    required this.order,
  });

  /// Stable key used in storage. Never rename.
  final String id;
  final String name;
  final String abbreviation;
  final Testament testament;
  final int chapters;

  /// 0-based canonical position, Genesis = 0, Revelation = 65.
  final int order;
}

