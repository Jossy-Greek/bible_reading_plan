/// 929 Old Testament + 260 New Testament.
const int kTotalChapters = 1189;

final Map<String, BibleBook> _byId = {for (final b in kBibleBooks) b.id: b};

/// Look a book up by [BibleBook.id]. Throws on an unknown id: ids are static
/// data, so an unknown one is a programming error, not user input.
BibleBook bookById(String id) =>
    _byId[id] ?? (throw ArgumentError.value(id, 'id', 'unknown Bible book'));

Iterable<BibleBook> booksIn(Testament t) =>
    kBibleBooks.where((b) => b.testament == t);
